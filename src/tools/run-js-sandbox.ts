/** Only runtime files are imported; their parent directories never enter the sandbox. */
export function buildRunJsBwrapArgs(execPath: string, wrapperPath: string, codePath: string): string[] {
	return [
		"--unshare-all",
		"--die-with-parent",
		"--new-session",
		"--ro-bind",
		"/usr",
		"/usr",
		"--ro-bind-try",
		"/lib",
		"/lib",
		"--ro-bind-try",
		"/lib64",
		"/lib64",
		"--ro-bind-try",
		"/etc/ld.so.cache",
		"/etc/ld.so.cache",
		"--dir",
		"/runjs",
		"--ro-bind",
		execPath,
		"/runjs/bun",
		"--ro-bind",
		wrapperPath,
		"/runjs/wrapper.mjs",
		"--ro-bind",
		codePath,
		"/runjs/code.js",
		"--tmpfs",
		"/tmp",
		"--proc",
		"/proc",
		"--dev",
		"/dev",
		"--chdir",
		"/tmp",
		"--",
		"/runjs/bun",
		"--smol",
		"/runjs/wrapper.mjs",
		"/runjs/code.js",
	];
}
